test('stateful tooling and unsupported extension options fail at import; inactive bindings are ignored', () => {
  const doc = preset({ ToolBindings: { identity: { enabled: true, code: 'return {};' } }, ChatSquash: { enabled: true, parse_clewd: true } });
  const report = inspectPreset(doc, settings);
  assert.ok(report.blockers.some(x => x.includes('consumeToolCalls')));
  assert.ok(report.blockers.some(x => x.includes('parse_clewd')));
  doc.prompt_order[0].order[0].enabled = false;
  assert.ok(!inspectPreset(doc, settings).blockers.some(x => x.includes('consumeToolCalls')));
});

test('unknown tools, malformed arguments, output rejection, held output and empty output never return prose', () => {
  const doc = preset({ OutputPreprocessing: { consumeToolCalls: true, toolCallFormatter: { enabled: true, script: '() => "must not recover"' } } });
  assert.throws(() => output(doc, { toolCalls: [{ name: 'unknown', arguments: '{}' }] }), /未声明/);
  assert.throws(() => processOutput({ document: doc, protocol: 'spreset', toolNames: ['known'], response: { toolCalls: [{ name: 'known', arguments: '{' }] } }), /JSON/);
  for (const script of ['() => ({output:"partial",hold:"more"})', '()=>({output:"rejected",state:{rejected:true}})', '()=>({output:"",hold:""})']) {
    doc.extensions.SPreset.OutputPreprocessing = { enabled: true, script };
    assert.throws(() => output(doc, { text: '原始正文' }), /hold|拒绝|为空/);
  }
});

test('legacy mode settings cannot bypass SPreset request or output processing', () => {
  const doc = preset({ FinalRequestProcessing: { enabled: true, script: '() => {throw Error("request hook");}' }, OutputPreprocessing: { enabled: true, script: '() => {throw Error("output hook");}' } });
  for (const adapter of ['st', 'auto', 'spreset']) {
    assert.equal(inspectPreset(doc, { adapter }).protocol, 'spreset');
    assert.throws(() => compilePreset(doc, compilerMaterials(materials), { adapter }), /request hook/);
    assert.throws(() => processOutput({ document: doc, settings: { adapter }, response: { text: 'X' } }), /output hook/);
  }
});

test('an empty SPreset layer preserves all base ST messages, sampling controls and output regex', () => {
  const native = structuredClone(base), extended = preset({});
  for (const adapter of [undefined, 'st', 'spreset']) {
    const options = { ...settings, adapter };
    assert.deepEqual(compilePreset(extended, compilerMaterials(materials), options).request,
      compilePreset(native, compilerMaterials(materials), options).request);
    for (const document of [native, extended]) assert.equal(processOutput({ document, response: { text: 'X' }, settings: options }).text, 'XX');
  }
});

test('worker cancellation and deadline bound a preset script before dispatch', async () => {
  const doc = preset({ FinalRequestProcessing: { enabled: true, script: '() => {while(true){}}' } });
  const controller = new AbortController();
  const promise = runCompiler('compile', { document: doc, materials: compilerMaterials(materials), settings }, { signal: controller.signal });
  setTimeout(() => controller.abort(new Error('用户取消脚本')), 60);
  await assert.rejects(promise, /用户取消脚本/);
  await assert.rejects(runCompiler('compile', { document: doc, materials: compilerMaterials(materials), settings }, { timeout: 80 }), /超时/);
});

test('optional local preset is diagnosed without executing unsupported protocols or copying its contents', { skip: !process.env.STCONTEXT_COMPAT_FIXTURE }, async t => {
  const doc = parsePreset(await readFile(process.env.STCONTEXT_COMPAT_FIXTURE, 'utf8'));
  const report = inspectPreset(doc, settings);
  t.diagnostic(report.protocol + ': ' + (report.blockers.length ? report.blockers.join('；') : 'static checks passed'));
  if (report.blockers.length) await assert.rejects(runCompiler('compile', { document: doc, materials: compilerMaterials(materials), settings }));
  else {
    const result = await runCompiler('compile', { document: doc, materials: compilerMaterials(materials), settings });
    assert.ok(result.request.messages.length);
    for (const row of materials.history) assert.ok(JSON.stringify(result.request).includes(row.text));
  }
});
