import test from 'node:test';
import assert from 'node:assert/strict';
import { compilePreset, inspectPreset, processOutput } from '../lib/preset.mjs';
import { runCompiler } from '../lib/worker-client.mjs';
import { compilerMaterials } from '../lib/materials.mjs';
import { preset as base, materials } from './fixtures/materials.mjs';
import { readFile } from 'node:fs/promises';
import { parsePreset } from '../lib/preset.mjs';

const settings = { model: { provider: 'fixture', model: 'story' } };
function preset(config = {}) {
  const doc = structuredClone(base);
  doc.extensions.SPreset = config;
  return doc;
}
const compile = doc => compilePreset(doc, compilerMaterials(materials), settings);
function output(doc, response, compiled = compile(doc)) {
  return processOutput({ document: doc, response, protocol: compiled.report.protocol, toolNames: (compiled.request.tools || []).map(t => t.name) });
}

test('generic hooks merge, transform final requests, format tools and apply output regex exactly once', () => {
  const doc = preset({
    ChatSquash: { enabled: true, role: 'system', user_prefix: '玩家 {{user}}：', char_prefix: '角色：',
      squashed_post_script_enable: true, squashed_post_script: 'text => "BEGIN\\n" + text + "\\nEND"' },
    ToolBindings: { identity: { enabled: true, editorMode: 'form', form: { name: 'return_story', description: '正文输出', parameters: [{ name: 'body', type: 'string', required: true }], actionBody: 'throw new Error("never run")' } } },
    FinalRequestProcessing: { enabled: true, script: '({ request }) => { request.tools[0].function.description += "\\n" + request.messages.map(m=>m.content).join("\\n"); request.messages=[{role:"user",content:"继续"}]; request.tool_choice="auto"; return request; }' },
    OutputPreprocessing: { enabled: true, consumeToolCalls: true,
      toolCallFormatter: { enabled: true, script: '({calls,defaultText}) => calls.length ? "<game>" + JSON.parse(calls[0].arguments).body + "</game>" : defaultText' },
      script: '({buffer,final,state}) => ({output: buffer + (final ? "!" : "?"), hold:"", state})' },
  });
  const compiled = compile(doc);
  assert.equal(compiled.report.protocol, 'spreset');
  assert.deepEqual(compiled.request.messages, [{ role: 'user', content: '继续' }]);
  const description = compiled.request.tools[0].description;
  for (const value of [...materials.history.map(m => m.text), ...materials.context.map(m => m.text), materials.input.text]) assert.ok(description.includes(value), value);
  assert.ok(description.includes('玩家 测试玩家：'));
  assert.equal(output(doc, { text: '', toolCalls: [{ name: 'return_story', arguments: '{"body":"X"}' }] }, compiled).text, '<game>XX</game>!');
  assert.equal(output(doc, { text: 'X', toolCalls: [] }, compiled).text, 'XX!');
});

test('tool declarations can be generated by a restricted pure function body; actions never execute', () => {
  const doc = preset({ ToolBindings: { identity: { enabled: true, code: 'return {name:"body",description:"story",parameters:{type:"object",properties:{text:{type:"string"}}},action:()=>{throw Error("never")} };' } },
    OutputPreprocessing: { consumeToolCalls: true, toolCallFormatter: { enabled: true, script: '({calls}) => calls[0].arguments.text' } } });
  const compiled = compile(doc);
  assert.deepEqual(Object.keys(compiled.request.tools[0]), ['name', 'description', 'parameters']);
  assert.equal(output(doc, { toolCalls: [{ name: 'body', arguments: { text: '测试正文' } }] }, compiled).text, '测试正文');
});

test('static import diagnoses hooks and protocols without running preset code', () => {
  const doc = preset({ FinalRequestProcessing: { enabled: true, script: '({request}) => { throw Error("not during import"); }' } });
  assert.equal(inspectPreset(doc, settings).blockers.length, 0);
  assert.throws(() => compile(doc), /not during import/);
  doc.extensions.SPreset.FinalRequestProcessing.script = '({request}) => { request.tool_choice="required"; request.messages=[{role:"assistant",tool_calls:[]}]; return request; }';
  const report = inspectPreset(doc, settings);
  assert.equal(report.blockers.length, 0);
  assert.ok(report.warnings.some(x => x.includes('tool_choice=required') && x.includes('tool_calls')));
  assert.throws(() => compile(doc), /非空工具调用数组|消息正文/);
  doc.extensions.SPreset.FinalRequestProcessing.script = '({request}) => {';
  assert.ok(inspectPreset(doc, settings).blockers.some(x => x.includes('语法')));
});

test('SPreset hooks and local helper scripts are detected while uploads remain disabled', () => {
  const doc = preset({ LogUpload: { enabled: true, url: 'https://example.invalid' } });
  doc.extensions.tavern_helper = { scripts: [{ enabled: true, name: 'remote', content: 'throw Error("never evaluate")' }] };
  const report = inspectPreset(doc, settings);
  assert.equal(report.blockers.length, 0);
  assert.equal(report.protocol, 'spreset');
  assert.ok(report.warnings.some(x => x.includes('受限助手环境')));
  assert.ok(report.warnings.some(x => x.includes('日志上传已禁用')));
  assert.throws(() => compile(doc), /never evaluate/);
});

test('final request scripts cannot remove or alter frozen history, inputs, requirements or state', () => {
  for (const body of ['request.messages=[];', 'request.messages=[{role:"user",content:"replacement"}];',
    'request.messages=request.messages.map(m=>({...m,content:m.content.replace("完整历史正文", "摘要")}));']) {
    const doc = preset({ FinalRequestProcessing: { enabled: true, script: '({request})=>{' + body + 'return request;}' } });
    assert.throws(() => compile(doc), /完整历史保护|完整 messages/);
  }
});

test('conditional merging, separators and history groups preserve complete source text', () => {
  const doc = preset({ ChatSquash: { enabled: true, conditional_enabled: true, conditional_tag: '<merge>', separate_chat_history: true,
    enable_squashed_separator: true, squashed_separator_string: '<sep>', role: 'user' } });
  const unmerged = compile(doc);
  assert.ok(unmerged.request.messages.length > 3);
  doc.prompts[1].content += '<merge><sep>tail';
  const merged = compile(doc);
  assert.ok(merged.request.messages.length < unmerged.request.messages.length);
  assert.ok(merged.request.messages.every(m => m.role === 'user'));
  for (const row of materials.history) assert.ok(merged.request.messages.some(m => m.content.includes(row.text)));
});

test('model route, frozen controls and unexpected wire fields cannot be replaced by scripts', () => {
  for (const body of ['request.model="other";', 'request.max_tokens=1;', 'request.temperature=0;', 'request.url="https://example.invalid";',
    'request.messages[0].name="extra-field";', 'request.custom_include_body="{\\"extra\\":true}";', 'request["tool_"+"choice"]="required";']) {
    const doc = preset({ FinalRequestProcessing: { enabled: true, script: '({request})=>{' + body + 'return request;}' } });
    assert.throws(() => compile(doc), /冻结|协议|字段|强制工具/);
  }
});

